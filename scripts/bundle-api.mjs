import * as esbuild from 'esbuild';
import { mkdirSync } from 'fs';
import path from 'path';

const jobs = [
  { entry: 'src/functions/contact.ts', outfile: 'api/contact.js' },
  { entry: 'src/functions/orders/index.ts', outfile: 'api/orders/index.js' },
  { entry: 'src/functions/orders/[id].ts', outfile: 'api/orders/[id].js' },
  { entry: 'src/functions/products/index.ts', outfile: 'api/products/index.js' },
  { entry: 'src/functions/products/[id].ts', outfile: 'api/products/[id].js' },
];

for (const job of jobs) {
  mkdirSync(path.dirname(job.outfile), { recursive: true });
  await esbuild.build({
    entryPoints: [job.entry],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    outfile: job.outfile,
    banner: { js: '/* generated by scripts/bundle-api.mjs — do not edit */' },
    legalComments: 'none',
    logLevel: 'info',
  });
}

console.log(`Bundled ${jobs.length} API functions`);
