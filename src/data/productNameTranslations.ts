export function getLocalizedProductName(
  product: Pick<Product, 'id' | 'name' | 'nameTranslations'>,
  locale: string
): string {
  const lang = locale.split('-')[0];
  if (lang === 'en') return product.name;
  const key = lang as TranslatedLocale;
  const fromProduct = product.nameTranslations?.[key];
  if (fromProduct) return fromProduct;
  const fromCatalog = PRODUCT_NAME_TRANSLATIONS[product.id]?.[key];
  return fromCatalog || product.name;
}

export function buildNameTranslationsForProduct(id: string): Record<string, string> {
  const entry = PRODUCT_NAME_TRANSLATIONS[id];
  if (!entry) return {};
  return { ...entry };
}

